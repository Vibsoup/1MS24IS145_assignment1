import { ResearchPlan, LiteratureItem, ResearchBrief } from '../types/research';

export function downloadFile(filename: string, content: string, contentType: string) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function generateBriefTxt(brief: ResearchBrief, plan?: ResearchPlan | null): string {
  const dateStr = new Date(brief.generatedAt).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const divider = '='.repeat(76);
  const subDivider = '-'.repeat(76);

  let text = '';
  text += `${divider}\n`;
  text += `RESEARCHPILOT ACADEMIC RESEARCH BRIEF\n`;
  text += `Generated: ${dateStr}\n`;
  if (plan) {
    text += `Discipline: ${plan.discipline} | Academic Level: ${plan.researchLevel}\n`;
  }
  text += `${divider}\n\n`;

  text += `TITLE: ${brief.title.toUpperCase()}\n\n`;

  text += `${subDivider}\n`;
  text += `1. ABSTRACT\n`;
  text += `${subDivider}\n`;
  text += `${brief.abstract}\n\n`;

  text += `${subDivider}\n`;
  text += `2. INTRODUCTION & BACKGROUND\n`;
  text += `${subDivider}\n`;
  text += `${brief.introduction}\n\n`;

  text += `${subDivider}\n`;
  text += `3. RESEARCH QUESTION\n`;
  text += `${subDivider}\n`;
  text += `${brief.researchQuestion}\n\n`;

  text += `${subDivider}\n`;
  text += `4. RESEARCH OBJECTIVES\n`;
  text += `${subDivider}\n`;
  brief.researchObjectives.forEach((obj, idx) => {
    text += `[O${idx + 1}] ${obj}\n`;
  });
  text += '\n';

  text += `${subDivider}\n`;
  text += `5. SYNTHESIZED LITERATURE REVIEW\n`;
  text += `${subDivider}\n`;
  text += `${brief.literatureReview}\n\n`;

  text += `${subDivider}\n`;
  text += `6. PROPOSED METHODOLOGY\n`;
  text += `${subDivider}\n`;
  text += `${brief.proposedMethodology}\n\n`;

  text += `${subDivider}\n`;
  text += `7. EXPECTED CONTRIBUTIONS\n`;
  text += `${subDivider}\n`;
  brief.expectedContributions.forEach((contrib, idx) => {
    text += `[C${idx + 1}] ${contrib}\n`;
  });
  text += '\n';

  text += `${subDivider}\n`;
  text += `8. METHODOLOGICAL LIMITATIONS & SCOPE CONSTRAINTS\n`;
  text += `${subDivider}\n`;
  brief.limitations.forEach((lim, idx) => {
    text += `[L${idx + 1}] ${lim}\n`;
  });
  text += '\n';

  text += `${subDivider}\n`;
  text += `9. REFERENCES & BIBLIOGRAPHIC SEARCH VECTORS\n`;
  text += `${subDivider}\n`;
  brief.references.forEach((ref, idx) => {
    const originLabel = ref.sourceOrigin === 'user_provided' ? 'USER-SUPPLIED SOURCE' : 'SUGGESTED SEARCH VECTOR (UNVERIFIED)';
    const verifiedStatus = ref.verified ? 'VERIFIED METADATA' : 'UNVERIFIED / ESTIMATED';
    text += `[${idx + 1}] ${ref.citation}\n`;
    text += `    Classification: ${originLabel} | Status: ${verifiedStatus}\n`;
    if (ref.notes) {
      text += `    Notes: ${ref.notes}\n`;
    }
    text += '\n';
  });

  text += `${divider}\n`;
  text += `Notice: Generated by ResearchPilot. All proposed methodologies are intended for investigative planning and do not substitute for institutional IRB or peer-review validation.\n`;
  text += `${divider}\n`;

  return text;
}

export function generateExportJson(
  plan: ResearchPlan | null,
  literatureList: LiteratureItem[],
  brief: ResearchBrief | null
): string {
  const exportData = {
    metadata: {
      generator: 'ResearchPilot',
      version: '1.0.0',
      exported_at: new Date().toISOString(),
      academic_integrity_declaration: 'Research gaps and methodology are strictly distinguished between hypothetical proposals and empirical literature.',
    },
    topic: plan?.originalTopic || 'Untitled Project',
    discipline: plan?.discipline || 'General',
    research_level: plan?.researchLevel || 'Undergraduate',
    research_question: brief?.researchQuestion || plan?.refinedQuestion || '',
    question_rationale: plan?.questionRationale || '',
    objectives: brief?.researchObjectives || plan?.objectives || [],
    keywords: plan?.keywords || [],
    search_queries: plan?.searchQueries || [],
    methodology: {
      recommended: plan?.recommendedMethodology || null,
      proposed_section: brief?.proposedMethodology || null,
    },
    research_gaps: plan?.researchGaps || [],
    outline: plan?.outline || [],
    literature_analysis: literatureList.map((item) => ({
      id: item.id,
      title: item.title,
      authors: item.authors,
      year: item.year,
      venue: item.venue,
      doi: item.doi,
      summary: item.analysis?.summary,
      objectives: item.analysis?.objectives,
      methodology: item.analysis?.methodology,
      main_findings: item.analysis?.mainFindings,
      reported_metrics: item.analysis?.reportedAccuracyOrMetrics,
      limitations: item.analysis?.limitations,
      limitations_type: item.analysis?.limitationsType,
      relevance_to_topic: item.analysis?.relevanceToTopic,
      verified_metadata: item.analysis?.verifiedMetadata,
    })),
    brief: brief
      ? {
          title: brief.title,
          abstract: brief.abstract,
          introduction: brief.introduction,
          literature_review: brief.literatureReview,
          expected_contributions: brief.expectedContributions,
          limitations: brief.limitations,
        }
      : null,
    references: brief?.references || [],
  };

  return JSON.stringify(exportData, null, 2);
}

export function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .substring(0, 40);
}
